-- VTAB Ticket Center 1.0.0 - non-destructive Supabase/PostgreSQL migration
create extension if not exists pgcrypto;

create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  title varchar(255) not null,
  description text not null,
  steps_to_reproduce text,
  category varchar(50) not null default 'bug' check (category in ('bug','crash','ui','performance','feature')),
  severity varchar(20) not null default 'medium' check (severity in ('low','medium','high','critical')),
  status varchar(30) not null default 'NEW' check (status in ('NEW','ASSIGNED','IN_PROGRESS','RESOLVED_BY_DEV','PENDING_ADMIN_SIGN_OFF','REOPENED','CLOSED')),
  source varchar(30) not null default 'desktop_exe',
  app_version varchar(50) not null,
  os_info jsonb not null default '{}'::jsonb,
  diagnostic_logs text,
  workspace_id text,
  reporter_user_id text not null,
  reporter_email varchar(255) not null,
  assigned_dev_id text,
  dev_resolved_at timestamptz,
  dev_resolution_notes text,
  fixed_in_build varchar(50),
  commit_reference varchar(255),
  admin_reviewed_by text,
  admin_closed_at timestamptz,
  admin_feedback_notes text,
  user_experience_verified boolean not null default false,
  user_satisfaction_rating int check (user_satisfaction_rating between 1 and 5),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ticket_attachments (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  file_name varchar(255) not null,
  file_url text not null,
  file_type varchar(100),
  file_size_bytes bigint,
  uploaded_by text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.ticket_timeline (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  actor_id text not null,
  actor_role varchar(20) not null check (actor_role in ('user','developer','admin','system')),
  event_type varchar(50) not null,
  old_status varchar(30),
  new_status varchar(30),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.ticket_comments (
  id uuid primary key default gen_random_uuid(),
  ticket_id uuid not null references public.tickets(id) on delete cascade,
  author_id text not null,
  author_role varchar(20) not null,
  body text not null,
  is_internal boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists tickets_status_idx on public.tickets(status, updated_at desc);
create index if not exists tickets_reporter_idx on public.tickets(reporter_user_id, updated_at desc);
create index if not exists tickets_assignee_idx on public.tickets(assigned_dev_id, updated_at desc);
create index if not exists ticket_timeline_ticket_idx on public.ticket_timeline(ticket_id, created_at);

insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types)
