alter table public.tickets enable row level security;
alter table public.ticket_attachments enable row level security;
alter table public.ticket_timeline enable row level security;
alter table public.ticket_comments enable row level security;

create or replace function public.ticket_role() returns text language sql stable as $$
  select coalesce(auth.jwt()->'app_metadata'->>'ticket_role', 'user');
$$;

drop policy if exists tickets_select_policy on public.tickets;
create policy tickets_select_policy on public.tickets for select using (
  reporter_user_id = auth.uid()::text or public.ticket_role() in ('developer','admin')
);
drop policy if exists tickets_insert_policy on public.tickets;
create policy tickets_insert_policy on public.tickets for insert with check (
  reporter_user_id = auth.uid()::text
);
drop policy if exists tickets_update_staff_policy on public.tickets;
create policy tickets_update_staff_policy on public.tickets for update using (
  public.ticket_role() in ('developer','admin')
);

drop policy if exists ticket_attachments_select_policy on public.ticket_attachments;
create policy ticket_attachments_select_policy on public.ticket_attachments for select using (
  exists(
    select 1 from public.tickets t
    where t.id = ticket_id
      and (t.reporter_user_id = auth.uid()::text or public.ticket_role() in ('developer','admin'))
  )
);
drop policy if exists ticket_attachments_insert_policy on public.ticket_attachments;
create policy ticket_attachments_insert_policy on public.ticket_attachments for insert with check (
  uploaded_by = auth.uid()::text
  and exists(
    select 1 from public.tickets t
    where t.id = ticket_id
      and (t.reporter_user_id = auth.uid()::text or public.ticket_role() in ('developer','admin'))
  )
);

drop policy if exists ticket_timeline_select_policy on public.ticket_timeline;
create policy ticket_timeline_select_policy on public.ticket_timeline for select using (
  exists(
    select 1 from public.tickets t
    where t.id = ticket_id
      and (t.reporter_user_id = auth.uid()::text or public.ticket_role() in ('developer','admin'))
  )
);
drop policy if exists ticket_comments_select_policy on public.ticket_comments;
create policy ticket_comments_select_policy on public.ticket_comments for select using (
  (not is_internal or public.ticket_role() in ('developer','admin'))
  and exists(
    select 1 from public.tickets t
    where t.id = ticket_id
      and (t.reporter_user_id = auth.uid()::text or public.ticket_role() in ('developer','admin'))
  )
);

-- Final closure is database-governed as well as API-governed.
create or replace function public.enforce_ticket_closure() returns trigger language plpgsql security definer as $$
begin
  if new.status = 'CLOSED' and old.status is distinct from 'CLOSED' then
    if public.ticket_role() <> 'admin'
       and coalesce(current_setting('app.ticket_actor_role', true), '') <> 'admin' then
      raise exception 'Only a ticket administrator can close a ticket';
    end if;
    if not new.user_experience_verified or new.admin_feedback_notes is null then
      raise exception 'User experience verification and closure notes are required';
    end if;
  end if;
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists ticket_closure_guard on public.tickets;
create trigger ticket_closure_guard
  before update on public.tickets
  for each row execute function public.enforce_ticket_closure();

grant all on table public.tickets, public.ticket_attachments, public.ticket_timeline, public.ticket_comments to postgres, service_role;
grant all on all sequences in schema public to postgres, service_role;

